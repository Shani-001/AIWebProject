import json
import csv
import io
from typing import List, Dict, Any


def export_findings_to_csv(signals: List[Dict[str, Any]]) -> str:
    """
    Exports a list of signals to a CSV formatted string with source URLs and evidence quotes.
    """
    output = io.StringIO()
    fields = [
        "category",
        "summary",
        "theme_name",
        "relevance_score",
        "urgency_score",
        "confidence_score",
        "evidence",
        "reasoning",
        "source_url",
        "evidence_verified",
        "extraction_method"
    ]
    writer = csv.DictWriter(output, fieldnames=fields, extrasaction="ignore")
    writer.writeheader()

    for s in signals:
        writer.writerow(s)

    return output.getvalue()


def export_findings_to_json(session: Dict[str, Any], signals: List[Dict[str, Any]], opportunities: List[Dict[str, Any]]) -> str:
    """
    Exports session findings and opportunities to formatted JSON string.
    """
    payload = {
        "session": {
            "id": session.get("id"),
            "topic": session.get("topic"),
            "keywords": session.get("keywords"),
            "ai_provider": session.get("ai_provider"),
            "created_at": session.get("created_at"),
            "pages_crawled_count": session.get("pages_crawled_count"),
            "signals_count": session.get("signals_count"),
            "domains_count": session.get("domains_count"),
            "summary_note": session.get("summary_note")
        },
        "opportunities": opportunities,
        "signals": signals
    }
    return json.dumps(payload, indent=2)


def generate_one_page_report_markdown(
    session: Dict[str, Any],
    opportunities: List[Dict[str, Any]],
    pages_count: int,
    domains_covered: List[str]
) -> str:
    """
    Generates a professional Markdown Executive Findings Report.
    """
    topic = session.get("topic", "Market Opportunity Research")
    provider = session.get("ai_provider", "Groq / Gemini")
    created = session.get("created_at", "N/A")

    dom_list_str = ", ".join(domains_covered[:6]) if domains_covered else "Multiple public domains"

    md = f"""# Executive Findings Report: {topic}
**AI Web Signal Hunter Intelligence Brief**  
*Generated on:* {created} | *AI Provider:* {provider.upper()} | *Pages Crawled:* {pages_count} | *Domains Covered:* {dom_list_str}

---

## 1. Executive Summary
This report presents verified, evidence-backed market signals extracted from public web sources regarding **"{topic}"**.
All findings reflect real content from {pages_count} crawled and cleaned pages. Each opportunity is evaluated using our transparent scoring methodology:

$$\\text{{Opportunity Score}} = 0.30 \\times \\text{{Relevance}} + 0.25 \\times \\text{{Urgency}} + 0.20 \\times \\text{{Confidence}} + 0.15 \\times \\text{{Frequency}} + 0.10 \\times \\text{{Recency}}$$

---

## 2. Top Five Discovered Opportunities

"""

    for idx, opp in enumerate(opportunities[:5], 1):
        title = opp.get("title", opp.get("theme_name", f"Opportunity {idx}"))
        score = opp.get("opportunity_score", 0.0)
        source_count = opp.get("source_count", 0)
        what = opp.get("what_is_happening", "")
        who = opp.get("who_has_problem", "")
        why = opp.get("why_it_matters", "")
        solution = opp.get("potential_solution", "")
        validation = opp.get("validation_step", "")

        brief_data = opp.get("brief_json") or {}
        if isinstance(brief_data, str):
            try:
                brief_data = json.loads(brief_data)
            except Exception:
                brief_data = {}

        evidence_items = brief_data.get("evidence_list", [])

        md += f"""### {idx}. {title} (Score: {score} / 100)
- **Supporting Sources:** {source_count} independent sources
- **What is happening:** {what}
- **Who has the problem:** {who}
- **Why it matters now:** {why}
- **Recommended Solution Angle:** {solution}
- **Actionable Validation Step:** {validation}

**Supporting Evidence Excerpts:**
"""
        if evidence_items:
            for ev in evidence_items[:2]:
                text = ev.get("text", "")
                url = ev.get("url", "#")
                md += f"> \"{text}\"\n> — [Source Link]({url})\n\n"
        else:
            md += "> Direct citations recorded in comprehensive data ledger.\n\n"

        md += "---\n\n"

    md += """## 3. Crawl Integrity & Responsible Research Notes
- **Verification:** All evidence quotes are exact substrings or fuzzy matches directly derived from crawled pages. No quotes are fabricated.
- **Access Compliance:** Crawling strictly respected robots.txt, politeness rate limits, and public content boundaries.
- **Next Actions:** Validate the top opportunity with customer discovery interviews and prototype testing.

*Generated by AI Web Signal Hunter.*
"""
    return md
